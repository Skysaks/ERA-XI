/**
 * DATASET AUDIT — structural and editorial checks over every team era and PlayerEra.
 *
 *   node scripts/run-ts.mjs scripts/data-audit.ts            # prints the report, exit 1 on errors
 *   OUT=docs/data-quality.md node scripts/run-ts.mjs scripts/data-audit.ts
 *
 * The checks live in src/data/validate.ts (shared with `tests/data-integrity.test.ts`, so
 * `npm test` fails on any critical error). Errors block a release; warnings are for editorial review.
 */
import { writeFileSync } from "node:fs";
import { ALL_CLUB_ERAS, ALL_PLAYER_IDS, DATA_STATS, getClub, getPlayerEraMeta, loadNationality, nationOf, playerEraIdsOf } from "@/data";
import { validateDataset } from "@/data/validate";

const { errors, warnings, checked } = await validateDataset();
let multi = 0;
let versions = 0;
for (const pid of ALL_PLAYER_IDS) {
  const n = playerEraIdsOf(pid).length;
  if (n > 1) multi++;
  versions += n;
}

// ── nationality & metadata ──
await loadNationality();
const nat = { high: 0, medium: 0, low: 0, missing: 0 };
for (const pid of ALL_PLAYER_IDS) {
  const n = nationOf(pid);
  if (!n) nat.missing++;
  else nat[n.confidence]++;
}
const conf = { high: 0, medium: 0, low: 0 };
for (const e of ALL_CLUB_ERAS) for (const id of e.playerEraIds) conf[getPlayerEraMeta(id).ratingConfidence]++;

const byBucket = new Map<string, { eras: number; pe: number }>();
for (const e of ALL_CLUB_ERAS) {
  const b = byBucket.get(e.bucket) ?? { eras: 0, pe: 0 };
  b.eras++;
  b.pe += e.playerEraIds.length;
  byBucket.set(e.bucket, b);
}

let md = `# ERA XI — dataset quality report\n\nGenerated by \`scripts/data-audit.ts\`.\n\n`;
md += `## Size\n\n| unique players | PlayerEra versions | team eras | clubs | nations | players with 2+ versions |\n|---|---|---|---|---|---|\n| ${DATA_STATS.players} | ${versions} | ${DATA_STATS.eras} | ${DATA_STATS.clubs} | ${DATA_STATS.nations} | ${multi} |\n\n`;
md += `## Chronological coverage\n\n| period | eras | PlayerEras |\n|---|---|---|\n`;
for (const k of ["pre1980", "1980s", "1990s", "2000s", "2010s", "2020s"]) {
  const b = byBucket.get(k) ?? { eras: 0, pe: 0 };
  md += `| ${k === "pre1980" ? "1950s–70s" : k} | ${b.eras} | ${b.pe} |\n`;
}
md += `\n## Geographic coverage (by the team's country)\n\n| region | club eras | national eras | PlayerEras | share |\n|---|---|---|---|---|\n`;
{
  const SA = ["BRA", "ARG", "URU", "CHI", "COL", "PAR", "PER", "ECU", "VEN", "BOL"];
  const NA = ["MEX", "USA", "CAN", "CRC", "HON", "JAM", "TRI", "PAN", "SLV", "GUA", "CUB", "HAI"];
  const AF = ["SEN", "CIV", "CMR", "NGA", "GHA", "MAR", "ALG", "EGY", "TUN", "MLI", "GUI", "RSA", "ZAM", "CPV", "GAB", "TOG", "BFA", "COD", "ANG", "ZIM", "KEN", "MOZ", "LBR", "BEN", "GNB", "CHA"];
  const AS = ["JPN", "KOR", "AUS", "IRN", "KSA", "QAT", "CHN", "ISR", "NZL"];
  const regionOf = (c: string) => (SA.includes(c) ? "South America" : NA.includes(c) ? "North & Central America" : AF.includes(c) ? "Africa" : AS.includes(c) ? "Asia & Oceania" : "Europe");
  const rows = new Map<string, { club: number; nation: number; pe: number }>();
  let total = 0;
  for (const e of ALL_CLUB_ERAS) {
    const r = regionOf(getClub(e.clubId).country);
    const row = rows.get(r) ?? { club: 0, nation: 0, pe: 0 };
    row[e.kind]++;
    row.pe += e.playerEraIds.length;
    total += e.playerEraIds.length;
    rows.set(r, row);
  }
  for (const [r, v] of [...rows].sort((a, b) => b[1].pe - a[1].pe)) md += `| ${r} | ${v.club} | ${v.nation} | ${v.pe} | ${((100 * v.pe) / total).toFixed(1)}% |\n`;
}
md += `\n## Metadata coverage\n\n- Nationality: ${nat.high} high confidence, ${nat.medium} medium, ${nat.low} low, ${nat.missing} missing (of ${ALL_PLAYER_IDS.length}).\n`;
md += `- Rating confidence (internal, per PlayerEra): ${conf.high} high (core files), ${conf.medium} medium (expansion), ${conf.low} low (expansion, before 1980).\n`;
md += `- Rating version: r1 (ERA XI's own model: authored era level + role archetype + explicit adjustments → attributes → overall). No commercial game's ratings are copied.\n\n`;
md += `Checked: ${checked.eras} team eras, ${checked.playerEras} PlayerEras, ${checked.identities} identities, ${checked.teams} teams, ${checked.eraMeta} era contexts, ${checked.nationResults} tournament results.\n\n`;
md += `## Errors (${errors.length})\n\n${errors.length ? errors.map((x) => `- ${x}`).join("\n") : "None."}\n\n`;
md += `## Warnings for editorial review (${warnings.length})\n\n${warnings.map((x) => `- ${x}`).join("\n")}\n`;

if (process.env.OUT) writeFileSync(process.env.OUT, md);
console.log(md.split("## Warnings")[0]);
console.log(`warnings: ${warnings.length}`);
for (const w of warnings.slice(0, Number(process.env.SHOW ?? 40))) console.log("  ·", w);
process.exit(errors.length ? 1 : 0);
